#!/bin/bash
# Shared config loader and exclude list for the macdrive scripts.

_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_conf="$_here/../macdrive.conf"

if [ ! -f "$_conf" ]; then
  echo "ERROR: $_conf not found. Copy macdrive.conf.example to macdrive.conf and edit it."
  exit 64
fi

# shellcheck disable=SC1090
. "$_conf"

: "${DISTRO:=Ubuntu}"
: "${MOUNTPOINT:=/mnt/mac}"

for _req in HWID MOUNTPOINT LOCAL_WSL ARCHIVE_WSL; do
  if [ -z "${!_req}" ]; then
    echo "ERROR: $_req is not set in macdrive.conf"
    exit 64
  fi
done

# macOS bookkeeping that should never be synced. These are regenerated by the
# OS and copying them between machines causes nothing but churn.
MAC_EXCLUDES=(
  --exclude='.journal'
  --exclude='.journal_info_block'
  --exclude='.HFS+ Private Directory Data'
  --exclude='.Spotlight-V100'
  --exclude='.fseventsd'
  --exclude='.DocumentRevisions-V100'
  --exclude='.TemporaryItems'
  --exclude='.Trashes'
)

require_mounted () {
  if ! mountpoint -q "$MOUNTPOINT"; then
    echo "ERROR: the Mac drive is not mounted at $MOUNTPOINT."
    return 1
  fi
  return 0
}
